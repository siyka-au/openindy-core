/*!
 * \brief Geometry::Geometry
 * \param parent
 */
Geometry::Geometry(QObject* parent) : Feature(parent) {}

/*!
 * \brief Geometry::Geometry
 * \param copy
 * \param parent
 */
Geometry::Geometry(const Geometry& copy, QObject* parent)
    : Feature(copy, parent),
      activeMeasurementConfig(copy.activeMeasurementConfig),
      ijk(copy.ijk),
      isCommon(copy.isCommon),
      radius(copy.radius),
      simulationData(copy.simulationData),
      statistic(copy.statistic),
      xyz(copy.xyz) {
  // copy attributes

  // deliberately not copied: realises, observations, nominalSystem -
  // duplicating a feature must not duplicate what it realises, what
  // observed it, or which system it is nominal in
}

/*!
 * \brief Geometry::operator =
 * \param copy
 * \return
 */
Geometry& Geometry::operator=(const Geometry& copy) {
  // copy attributes
  this->isCommon = copy.isCommon;
  this->statistic = copy.statistic;
  this->simulationData = copy.simulationData;
  this->activeMeasurementConfig = copy.activeMeasurementConfig;

  this->xyz = copy.xyz;
  this->ijk = copy.ijk;
  this->radius = copy.radius;

  // deliberately not copied: realises, observations, nominalSystem - see
  // the copy constructor above

  return *this;
}

/*!
 * \brief Geometry::~Geometry
 */
Geometry::~Geometry() {
  // delete this geometry from the nominal list of its coordinate system,
  // if it was a nominal
  if (!this->nominalSystem.isNull()) {
    this->nominalSystem->removeNominal(this->selfFeature);
  }

  // delete this geometry from the target geometries list of any
  // observations that reference it
  for (const QPointer<Observation>& observation :
       oi::snapshot(this->observations)) {
    if (!observation.isNull()) {
      observation->removeTargetGeometry(this->id);
    }
  }

  // D19 applied to functions (Stage 7h): unregister from the owner's
  // ownedSubGeometries list, defensive symmetry with the nominalSystem
  // cleanup above. The expected path is the other direction -
  // OiJob::removeFeature cascade-deletes owned children *before* the
  // owner itself is destroyed - but this keeps the owner's list correct
  // even if an owned geometry is ever destroyed some other way.
  if (this->ownerFeature.has_value() && !this->ownerFeature->isNull()) {
    this->ownerFeature.value()->ownedSubGeometries.removeAll(
        QPointer<Geometry>(this));
  }
}

