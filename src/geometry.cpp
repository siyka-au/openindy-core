/*!
 * \brief Geometry::setOwnerFeature
 * D19 applied to functions (Stage 7h): record that this geometry is a
 * bound, read-only sub-geometry owned by `owner`, and register this
 * geometry on the owner's side too (getOwnedSubGeometries()) so the owner
 * can find, regenerate and cascade-delete it. Not a user edit - called
 * once by OiJob::addOwnedSubGeometry when the accessor is generated, and
 * by ProjectExchanger when a persisted <ownerFeature ref=.../> is
 * resolved on load - so it is not gated by rejectIfNotEditable.
 * \param owner
 * \return
 */
bool Geometry::setOwnerFeature(const oi::Guarded<Geometry>& owner) {
  if (owner.isNull() || owner.data() == this) {
    return false;
  }

  this->ownerFeature = owner;

  oi::Guarded<Geometry> self(this);
  if (!oi::contains(owner->ownedSubGeometries, self)) {
    owner->ownedSubGeometries.push_back(self);
  }

  this->notify(&FeatureObserver::onGeomOwnerFeatureChanged, this->id);

  return true;
}

