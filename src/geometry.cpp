/*!
 * \brief Geometry::getOwnerDescription
 * D19: a geometry produced by a FitFunction is owned by that fit and is
 * read-only - the fit regenerates it on every recompute, so a user edit
 * would just be overwritten (or worse, silently diverge until the next
 * recalc). Anything else - no producer yet, or a scalar-parameter-only
 * producer such as NominalPoint - is user-owned and editable. This is
 * what makes a nominal editable and an actual not, without a flag: it
 * falls out of which kind of function produced it.
 * \return
 */
std::optional<std::string> Geometry::getOwnerDescription() const {
  // Stage 7h: function-owned sub-geometry (a plane's normal line, its
  // origin point, ...) is owned by its owner FEATURE, not identified by
  // its producer function's type - the exact same ConstructFunction
  //(e.g. LineFromPlaneNormal) produces an independent, editable feature
  // when the user attaches it directly (D8) and a bound, read-only one
  // when OiJob::addOwnedSubGeometry attaches it and records the owner
  // here. Check this before the FitFunction case below: an owned
  // accessor's producer is never a FitFunction, but the two checks are
  // independent and this one is more specific.
  if (this->ownerFeature.has_value() && !this->ownerFeature->isNull()) {
    const std::string functionName =
        (this->producerFunction.has_value() &&
         !this->producerFunction->isNull())
            ? this->producerFunction.value()->getMetaData().name
            : std::string("its owner's function");
    return std::format("generated by \"{}\" on \"{}\"", functionName,
                       this->ownerFeature.value()->getFeatureName());
  }

  if (!this->producerFunction.has_value()) {
    return std::nullopt;
  }

  const oi::Guarded<Function> producer = this->producerFunction.value();
  if (producer.isNull() ||
      dynamic_cast<FitFunction*>(producer.data()) == nullptr) {
    return std::nullopt;
  }

  return std::format("its fit function \"{}\"", producer->getMetaData().name);
}

