/*!
 * \brief Geometry::recalc
 * D19 applied to functions (Stage 7h): snapshot this geometry's own value
 * before re-executing its function list, so that afterwards we can tell
 * whether it actually changed. Only then do we dirty this geometry's own
 * owned sub-geometry (getOwnedSubGeometries()) so the *next* pass of the
 * existing dependency-graph walk
 * (FeatureUpdater::recursiveFeatureRecalculation, which already visits an
 * owned child through the ordinary usedFor/previouslyNeeded edges set up
 * when it was generated) actually regenerates it. This is deliberately
 * not a second recalculation path - it only flips isUpdated back to
 * false; the existing walk does the rest. Reusing the ordinary
 * dependency graph, plus never dirtying on a no-op recalc, is what keeps
 * a project load from re-executing an owned accessor's construction
 * chain when nothing upstream actually changed (domain-model.md S1/S6).
 */
void Geometry::recalc() {
  const bool wasSolved = this->isSolved;
  const bool hadOwnedSubGeometries = !this->ownedSubGeometries.empty();
  const OiVec previousPosition =
      hadOwnedSubGeometries ? this->xyz.getVector() : OiVec();
  const OiVec previousDirection =
      hadOwnedSubGeometries ? this->ijk.getVector() : OiVec();
  const double previousRadius =
      hadOwnedSubGeometries ? this->radius.getRadius() : 0.0;

  Feature::recalc();

  // a geometry with a nominal system but no producer function yet (a
  // freshly created nominal before its first parameter entry) is
  // considered solved as soon as that system is the active one
  if (!this->producerFunction.has_value() && !this->nominalSystem.isNull() &&
      this->nominalSystem->getIsActiveCoordinateSystem()) {
    this->isSolved = true;
  }

  // reset statistic if not solved
  if (!this->isSolved) {
    this->statistic.reset();
  }

  // dirty owned sub-geometry only if something actually moved (or the
  // solved state itself flipped) - see method comment
  if (hadOwnedSubGeometries) {
    const bool valueChanged = (wasSolved != this->isSolved) ||
                              !(previousPosition == this->xyz.getVector()) ||
                              !(previousDirection == this->ijk.getVector()) ||
                              previousRadius != this->radius.getRadius();
    if (valueChanged) {
      for (const oi::Guarded<Geometry>& child :
           oi::snapshot(this->ownedSubGeometries)) {
        if (!child.isNull()) {
          child->setIsUpdated(false);
        }
      }
    }
  }
}

